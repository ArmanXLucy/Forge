import { useEffect, useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import {
  AlertTriangle,
  ArrowLeft,
  ArrowRight,
  Brain,
  Check,
  ChevronRight,
  Clock3,
  Cpu,
  Dumbbell,
  History,
  Lock,
  RefreshCw,
  ShieldCheck,
  Sparkles,
  Target,
  Unlock,
  Zap,
} from 'lucide-react'
import { toast } from 'sonner'
import { PageHeader, ProgressBar, SectionCard } from '../../components/dashboard/ui'
import { ProgressRing } from '../../components/ui/ProgressRing'
import { Badge } from '../../components/ui/Badge'
import { Button, buttonClasses } from '../../components/ui/Button'
import { useWorkoutRecommendation } from '../../features/workout-recommendation/hooks/useWorkoutRecommendation'
import { PlanSchedule } from '../../features/workout-recommendation/components/PlanSchedule'
import { preloadWorkoutModel } from '../../features/workout-recommendation/lib/inference'
import { MISSION_MAP } from '../../data/missions'
import { GOAL_LABELS, EXPERIENCE_LABELS } from '../../lib/constants'
import { formatDate } from '../../lib/utils'
import { cn } from '../../lib/utils'

export default function WorkoutRecommendationPage() {
  const rec = useWorkoutRecommendation()
  const {
    profile,
    readiness,
    active,
    plans,
    outdated,
    hydrated,
    loading,
    generating,
    error,
  } = rec
  const [viewingId, setViewingId] = useState<string | null>(null)
  const [actionError, setActionError] = useState<string | null>(null)

  const viewing = viewingId ? plans.find((plan) => plan.recommendationId === viewingId) ?? null : null
  const displayedPlan = viewing ?? active
  const displayedIsOld = Boolean(viewing && active && viewing.recommendationId !== active.recommendationId)

  const remaining = useMemo(
    () => readiness.remainingMissionIds.map((id) => MISSION_MAP[id]).filter(Boolean),
    [readiness.remainingMissionIds],
  )
  const nextMission = remaining[0] ?? null
  const progressPercent = Math.round(
    (readiness.completedMissions / Math.max(1, readiness.requiredMissions)) * 100,
  )
  const combinedError = actionError ?? error

  useEffect(() => {
    window.scrollTo({ top: 0, behavior: 'instant' as ScrollBehavior })
    preloadWorkoutModel()
  }, [])

  const handleGenerate = async () => {
    setActionError(null)
    try {
      const plan = await rec.generate()
      setViewingId(null)
      toast.success(`Plan generated: ${plan.predictedPlanCategory}`)
      window.scrollTo({ top: 0, behavior: 'smooth' })
    } catch (generateError) {
      const message =
        generateError instanceof Error ? generateError.message : 'The workout plan could not be generated.'
      setActionError(message)
      toast.error(message)
    }
  }

  if (!hydrated || loading) {
    return (
      <div>
        <PageHeader
          eyebrow="AI training"
          title={<>Your AI workout plan<span className="text-orange-500">.</span></>}
          subtitle="Loading your recommendation status…"
        />
        <div className="grid gap-3 lg:grid-cols-3">
          {[0, 1, 2].map((index) => (
            <div key={index} className="h-32 animate-pulse rounded-2xl border border-charcoal/10 bg-white" />
          ))}
        </div>
      </div>
    )
  }

  return (
    <div>
      <PageHeader
        eyebrow="AI training"
        title={
          <>
            Your AI workout plan<span className="text-orange-500">.</span>
          </>
        }
        subtitle="A weekly schedule built from your missions, experience, equipment and safety profile — generated by the Forge recommendation model running locally in your browser."
        actions={
          <div className="flex flex-wrap gap-2">
            <Link to="/dashboard/missions" className={buttonClasses('outline', 'sm')}>
              <Target className="h-3.5 w-3.5" /> Review missions
            </Link>
            {readiness.ready && (
              <button
                type="button"
                onClick={handleGenerate}
                disabled={generating}
                className={buttonClasses('primary', 'sm')}
              >
                {generating ? (
                  <>
                    <RefreshCw className="h-3.5 w-3.5 animate-spin" /> Generating…
                  </>
                ) : active ? (
                  <>
                    <RefreshCw className="h-3.5 w-3.5" /> Regenerate
                  </>
                ) : (
                  <>
                    <Sparkles className="h-3.5 w-3.5" /> Generate plan
                  </>
                )}
              </button>
            )}
          </div>
        }
      />

      {combinedError && (
        <div className="mb-4 flex items-start gap-3 rounded-xl border border-red-500/25 bg-red-50 p-4 text-[12px] leading-relaxed text-red-800">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" />
          <div>
            <p className="font-semibold">The plan could not be generated.</p>
            <p className="mt-1">{combinedError}</p>
            <p className="mt-1 text-[10px] text-red-700/70">
              No plan was saved. You can retry safely — the previous plan was not deleted.
            </p>
          </div>
        </div>
      )}

      {!readiness.ready ? (
        <LockedPanel
          progressPercent={progressPercent}
          completed={readiness.completedMissions}
          required={readiness.requiredMissions}
          remaining={remaining}
          missingAnswerMissions={readiness.missingAnswerMissions}
          invalidFields={readiness.invalidFields}
          warnings={readiness.warnings}
          nextMissionId={nextMission?.id ?? null}
          conditionText={
            readiness.missingAnswerMissions.length > 0
              ? 'Some missions were marked complete before answers were saved. Re-open those missions and save your answers to unlock the plan.'
              : null
          }
        />
      ) : (
        <>
          <ReadyPanel
            profile={profile}
            generating={generating}
            hasPlan={Boolean(active)}
            onGenerate={handleGenerate}
          />

          {displayedPlan ? (
            <div className="mt-4 grid gap-4 xl:grid-cols-[1.65fr_1fr]">
              <div className="space-y-4">
                <PlanHero plan={displayedPlan} outdated={!displayedIsOld && outdated} />
                {outdated && !displayedIsOld && (
                  <div className="flex flex-col gap-3 rounded-xl border border-amber-500/30 bg-amber-50 p-4 sm:flex-row sm:items-center sm:justify-between">
                    <div className="flex items-start gap-2.5">
                      <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-amber-600" />
                      <div>
                        <p className="text-[12px] font-semibold text-amber-900">
                          Your profile changed after this plan was generated.
                        </p>
                        <p className="mt-0.5 text-[11px] leading-relaxed text-amber-900/70">
                          Regenerate to use your latest mission answers. This version stays in your
                          history.
                        </p>
                      </div>
                    </div>
                    <Button size="sm" onClick={handleGenerate} disabled={generating}>
                      <RefreshCw className={cn('h-3.5 w-3.5', generating && 'animate-spin')} /> Regenerate
                    </Button>
                  </div>
                )}
                {displayedIsOld && (
                  <div className="flex items-center justify-between gap-3 rounded-xl border border-charcoal/15 bg-white p-3.5">
                    <p className="flex items-center gap-2 text-[11px] text-charcoal/50">
                      <History className="h-3.5 w-3.5" /> Viewing an earlier version of your plan.
                    </p>
                    <button
                      type="button"
                      onClick={() => setViewingId(null)}
                      className="inline-flex items-center gap-1 text-[10px] font-bold uppercase tracking-[0.1em] text-orange-600"
                    >
                      <ArrowLeft className="h-3 w-3" /> Active plan
                    </button>
                  </div>
                )}

                <SectionCard
                  eyebrow="Seven-day schedule"
                  title="Your week, day by day."
                  action={
                    <Badge tone="muted">
                      <Clock3 className="h-3 w-3" />
                      {displayedPlan.schedule
                        .filter((day) => day.kind !== 'rest')
                        .reduce((sum, day) => sum + day.estimatedDuration, 0)}{' '}
                      min total
                    </Badge>
                  }
                >
                  <PlanSchedule schedule={displayedPlan.schedule} />
                </SectionCard>
              </div>

              <aside className="space-y-4">
                <SafetyCard plan={displayedPlan} />
                <SectionCard
                  eyebrow="Model"
                  title="How this was generated."
                  action={<Brain className="h-4 w-4 text-charcoal/25" />}
                >
                  <dl className="space-y-2.5 text-[11px]">
                    <ModelRow label="Plan category" value={displayedPlan.predictedPlanCategory} />
                    <ModelRow
                      label="Confidence"
                      value={`${(displayedPlan.confidence * 100).toFixed(1)}%`}
                    />
                    <ModelRow label="Model version" value={displayedPlan.modelVersion} />
                    <ModelRow label="Inference" value={`${displayedPlan.inferenceMs} ms · ONNX Runtime Web`} />
                    <ModelRow
                      label="Generated"
                      value={formatDate(new Date(displayedPlan.createdAt), {
                        weekday: undefined,
                        year: 'numeric',
                      })}
                    />
                    <ModelRow label="Plan version" value={`v${displayedPlan.version}`} />
                  </dl>
                  <div className="mt-3 rounded-lg bg-ivory p-3">
                    <p className="text-[9px] font-bold uppercase tracking-[0.12em] text-charcoal/35">
                      Top model classes
                    </p>
                    <div className="mt-2 space-y-1.5">
                      {displayedPlan.classProbabilities.slice(0, 3).map((entry) => (
                        <div key={entry.label}>
                          <div className="flex items-center justify-between text-[10px]">
                            <span className="truncate pr-2 text-charcoal/55">{entry.label}</span>
                            <span className="font-semibold text-charcoal/70">
                              {(entry.probability * 100).toFixed(1)}%
                            </span>
                          </div>
                          <div className="mt-0.5 h-1 overflow-hidden rounded-full bg-charcoal/[0.06]">
                            <div
                              className="h-full rounded-full bg-orange-500"
                              style={{ width: `${Math.max(2, entry.probability * 100)}%` }}
                            />
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                </SectionCard>

                <SectionCard
                  eyebrow="History"
                  title={plans.length > 1 ? `${plans.length} saved versions.` : 'Version history'}
                  action={<History className="h-4 w-4 text-charcoal/25" />}
                >
                  <ul className="space-y-2">
                    {plans.map((plan) => (
                      <li key={plan.recommendationId}>
                        <button
                          type="button"
                          onClick={() => setViewingId(plan.recommendationId)}
                          className={cn(
                            'flex w-full items-center gap-2.5 rounded-lg border p-2.5 text-left transition-colors',
                            displayedPlan.recommendationId === plan.recommendationId
                              ? 'border-orange-500/30 bg-orange-500/[0.06]'
                              : 'border-charcoal/8 bg-white hover:border-charcoal/20',
                          )}
                        >
                          <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-md bg-ivory text-[10px] font-bold text-charcoal/50">
                            v{plan.version}
                          </span>
                          <span className="min-w-0 flex-1">
                            <span className="block truncate text-[11px] font-semibold text-charcoal">
                              {plan.predictedPlanCategory}
                            </span>
                            <span className="block text-[9px] text-charcoal/35">
                              {formatDate(new Date(plan.createdAt), {
                                weekday: undefined,
                                year: 'numeric',
                              })}
                              {plan.isActive ? ' · Active' : ''}
                            </span>
                          </span>
                          <ChevronRight className="h-3.5 w-3.5 shrink-0 text-charcoal/25" />
                        </button>
                      </li>
                    ))}
                  </ul>
                  <p className="mt-3 text-[9px] leading-relaxed text-charcoal/30">
                    Previous versions are preserved. Generating a new plan never overwrites history.
                  </p>
                </SectionCard>
              </aside>
            </div>
          ) : (
            <NoPlanPanel generating={generating} onGenerate={handleGenerate} />
          )}
        </>
      )}

      <div className="mt-5 flex flex-wrap items-center gap-x-4 gap-y-2 text-[9px] uppercase tracking-[0.1em] text-charcoal/25">
        <span className="inline-flex items-center gap-1.5">
          <Cpu className="h-3 w-3" /> ONNX Runtime Web · local inference
        </span>
        <span className="inline-flex items-center gap-1.5">
          <ShieldCheck className="h-3 w-3" /> Validated safety filters
        </span>
        <span className="inline-flex items-center gap-1.5">
          <Dumbbell className="h-3 w-3" /> 24 plan categories
        </span>
      </div>
    </div>
  )
}

function LockedPanel({
  progressPercent,
  completed,
  required,
  remaining,
  missingAnswerMissions,
  invalidFields,
  warnings,
  nextMissionId,
  conditionText,
}: {
  progressPercent: number
  completed: number
  required: number
  remaining: Array<(typeof MISSION_MAP)[string]>
  missingAnswerMissions: string[]
  invalidFields: string[]
  warnings: string[]
  nextMissionId: string | null
  conditionText: string | null
}) {
  return (
    <>
      <section className="relative overflow-hidden rounded-2xl bg-charcoal p-6 text-white sm:p-8">
        <div className="absolute -right-16 -top-16 h-64 w-64 rounded-full bg-orange-500/10 blur-3xl" />
        <div className="relative grid gap-7 lg:grid-cols-[1.5fr_1fr] lg:items-center">
          <div>
            <span className="eyebrow-light">
              <Lock className="h-3.5 w-3.5" /> Locked · mission gated
            </span>
            <h2 className="mt-3 max-w-xl font-display uppercase text-3xl leading-[0.95] sm:text-4xl">
              Your personalised plan is almost ready.
            </h2>
            <p className="mt-3 max-w-xl text-[12.5px] leading-relaxed text-white/55">
              Complete your fitness missions to unlock a workout plan tailored to your goals,
              experience, available equipment and physical limitations.
            </p>
            <div className="mt-5 flex flex-wrap items-center gap-3">
              <Link to="/dashboard/missions" className={buttonClasses('primary', 'sm')}>
                Complete my missions <ArrowRight className="h-3.5 w-3.5" />
              </Link>
              {nextMissionId && (
                <Link
                  to={`/dashboard/missions/${nextMissionId}`}
                  className={buttonClasses('outline-light', 'sm')}
                >
                  Resume next mission
                </Link>
              )}
            </div>
            <div className="mt-6 grid gap-3 border-t border-white/10 pt-4 sm:grid-cols-3">
              <div>
                <p className="text-[9px] uppercase tracking-[0.14em] text-white/30">Progress</p>
                <p className="mt-1 font-display uppercase text-xl">
                  {completed} <span className="text-sm text-white/35">of {required}</span>
                </p>
              </div>
              <div>
                <p className="text-[9px] uppercase tracking-[0.14em] text-white/30">Remaining</p>
                <p className="mt-1 font-display uppercase text-xl">{remaining.length}</p>
              </div>
              <div>
                <p className="text-[9px] uppercase tracking-[0.14em] text-white/30">AI model</p>
                <p className="mt-1 inline-flex items-center gap-1.5 font-display uppercase text-xl">
                  <Zap className="h-4 w-4 text-orange-400" /> Ready
                </p>
              </div>
            </div>
          </div>
          <div className="flex items-center justify-center">
            <ProgressRing value={progressPercent} size={132} strokeWidth={9}>
              <span className="font-display uppercase text-3xl leading-none">{progressPercent}%</span>
              <span className="mt-1 text-[8px] uppercase tracking-[0.12em] text-white/35">
                missions
              </span>
            </ProgressRing>
          </div>
        </div>
      </section>

      <div className="mt-4 grid gap-4 lg:grid-cols-[1.35fr_1fr]">
        <SectionCard
          eyebrow="Unlock checklist"
          title={`${completed} of ${required} missions completed.`}
          action={<Badge tone={completed === required ? 'green' : 'orange'}>{progressPercent}%</Badge>}
        >
          <ProgressBar value={progressPercent} className="mb-4" />
          {conditionText && (
            <div className="mb-3 rounded-lg border border-amber-500/30 bg-amber-50 p-3 text-[11px] leading-relaxed text-amber-900">
              {conditionText}
            </div>
          )}
          <ul className="divide-y divide-charcoal/5">
            {remaining.map((mission) => (
              <li key={mission.id} className="flex items-center gap-3 py-2.5 first:pt-0">
                <span className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-ivory text-[9px] font-bold text-charcoal/45">
                  {mission.number}
                </span>
                <span className="min-w-0 flex-1">
                  <span className="block text-[12px] font-semibold text-charcoal">{mission.title}</span>
                  <span className="block text-[10px] text-charcoal/35">
                    {mission.estimatedMinutes} min · {mission.xp} XP
                  </span>
                </span>
                <Link
                  to={`/dashboard/missions/${mission.id}`}
                  className="inline-flex items-center gap-1 text-[10px] font-bold uppercase tracking-[0.1em] text-orange-600"
                >
                  Start <ChevronRight className="h-3 w-3" />
                </Link>
              </li>
            ))}
            {remaining.length === 0 && (
              <li className="flex items-center gap-2 py-2 text-[12px] text-emerald-700">
                <Check className="h-4 w-4" /> All missions complete.
              </li>
            )}
          </ul>
          {missingAnswerMissions.length > 0 && (
            <div className="mt-3 rounded-lg border border-amber-500/30 bg-amber-50 p-3">
              <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-amber-800">
                Answers needed
              </p>
              <p className="mt-1 text-[11px] leading-relaxed text-amber-900/75">
                Re-open and save:{' '}
                {missingAnswerMissions.map((id) => MISSION_MAP[id]?.title ?? id).join(', ')}.
              </p>
            </div>
          )}
          {invalidFields.length > 0 && (
            <div className="mt-3 rounded-lg border border-red-500/25 bg-red-50 p-3">
              <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-red-700">
                Invalid profile data
              </p>
              <p className="mt-1 text-[11px] leading-relaxed text-red-800/75">
                {invalidFields.join(', ')}
              </p>
            </div>
          )}
        </SectionCard>

        <div className="space-y-4">
          <SectionCard eyebrow="What you will receive" title="A complete week — not a list of exercises.">
            <ul className="space-y-3">
              {[
                {
                  icon: Dumbbell,
                  title: 'A seven-day schedule',
                  detail: 'Training days matched to your availability, with recovery built in.',
                },
                {
                  icon: ShieldCheck,
                  title: 'Safety-filtered exercises',
                  detail: 'Movements are excluded when they conflict with recorded limitations.',
                },
                {
                  icon: Brain,
                  title: 'A validated plan category',
                  detail: 'The on-device ONNX model predicts one of 24 plan styles from your profile.',
                },
              ].map((item) => (
                <li key={item.title} className="flex items-start gap-2.5">
                  <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-orange-500/10 text-orange-600">
                    <item.icon className="h-4 w-4" />
                  </span>
                  <div>
                    <p className="text-[12px] font-semibold text-charcoal">{item.title}</p>
                    <p className="mt-0.5 text-[10.5px] leading-relaxed text-charcoal/45">{item.detail}</p>
                  </div>
                </li>
              ))}
            </ul>
          </SectionCard>
          {warnings.length > 0 && (
            <div className="rounded-xl border border-amber-500/25 bg-amber-50 p-3.5">
              <p className="flex items-center gap-1.5 text-[10px] font-bold uppercase tracking-[0.12em] text-amber-800">
                <AlertTriangle className="h-3.5 w-3.5" /> Safety notes
              </p>
              <ul className="mt-1.5 space-y-1">
                {warnings.map((warning) => (
                  <li key={warning} className="text-[10.5px] leading-relaxed text-amber-900/75">
                    {warning}
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      </div>
    </>
  )
}

function ReadyPanel({
  profile,
  generating,
  hasPlan,
  onGenerate,
}: {
  profile: ReturnType<typeof useWorkoutRecommendation>['profile']
  generating: boolean
  hasPlan: boolean
  onGenerate: () => void
}) {
  return (
    <section className="rounded-2xl border border-emerald-600/20 bg-white p-5 sm:p-6">
      <div className="flex flex-col gap-5 md:flex-row md:items-center md:justify-between">
        <div className="flex items-start gap-3">
          <span className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-emerald-600 text-white">
            <Unlock className="h-5 w-5" />
          </span>
          <div>
            <span className="inline-flex items-center gap-1 rounded-full bg-emerald-50 px-2 py-0.5 text-[8px] font-bold uppercase tracking-[0.14em] text-emerald-700">
              <Check className="h-2.5 w-2.5" /> Unlocked
            </span>
            <h2 className="mt-1.5 font-display uppercase text-xl leading-none text-charcoal">
              {hasPlan ? 'Your plan is ready.' : 'Ready to build your plan.'}
            </h2>
            <p className="mt-1 max-w-xl text-[11px] leading-relaxed text-charcoal/45">
              {hasPlan
                ? 'Regenerate to reflect your latest mission answers, or review the schedule below.'
                : 'All required missions are complete and validated. Generate your first personalised week.'}
            </p>
            <div className="mt-2.5 flex flex-wrap gap-1.5">
              {profile && (
                <>
                  <Badge tone="muted">
                    <Target className="h-3 w-3" /> {GOAL_LABELS[profile.goal]}
                  </Badge>
                  <Badge tone="muted">
                    <Dumbbell className="h-3 w-3" /> {EXPERIENCE_LABELS[profile.experience]}
                  </Badge>
                  <Badge tone="muted">
                    <Clock3 className="h-3 w-3" /> {profile.workoutDays.length} preferred days
                  </Badge>
                </>
              )}
            </div>
          </div>
        </div>
        <Button onClick={onGenerate} disabled={generating} size="sm" className="shrink-0">
          {generating ? (
            <>
              <RefreshCw className="h-3.5 w-3.5 animate-spin" /> Generating…
            </>
          ) : (
            <>
              <Sparkles className="h-3.5 w-3.5" /> {hasPlan ? 'Regenerate plan' : 'Generate my plan'}
            </>
          )}
        </Button>
      </div>
    </section>
  )
}

