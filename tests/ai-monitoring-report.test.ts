import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { sanitizeMonitoringMessage } from '../src/services/monitoring/aiMonitoring'
import type { EvaluationReport } from '../src/features/admin/useAIEvaluation'

const report = JSON.parse(
  readFileSync('public/models/evaluation_report.json', 'utf8'),
) as EvaluationReport

describe('monitoring message sanitisation', () => {
  it('strips URLs, emails and token-like strings', () => {
    const clean = sanitizeMonitoringMessage(
      'Failed at https://example.com/a?token=secret for arman@example.com token ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789',
    )
    expect(clean).toBe('Failed at [url] for [email] token [redacted]')
  })

  it('collapses whitespace, trims and caps at 240 characters', () => {
    const clean = sanitizeMonitoringMessage('  a\n\n b   c ' + 'fail '.repeat(80))
    expect(clean?.startsWith('a b c')).toBe(true)
    expect(clean?.length).toBe(240)
  })

  it('returns undefined for empty or non-string values', () => {
    expect(sanitizeMonitoringMessage('   ')).toBeUndefined()
    expect(sanitizeMonitoringMessage(42)).toBeUndefined()
    expect(sanitizeMonitoringMessage(null)).toBeUndefined()
  })
})

describe('official evaluation report', () => {
  it('is generated by the repository script and marked official', () => {
    expect(report.schemaVersion).toBe(1)
    expect(report.official).toBe(true)
    expect(report.generatedBy).toBe('scripts/evaluate-models.py')
    expect(new Date(report.generatedAt).getTime()).toBeGreaterThan(0)
  })

  it('pins every deployed artifact by hash and size', () => {
    for (const model of report.models) {
      const bytes = readFileSync('public/models/' + model.fileName)
      expect(bytes.byteLength).toBe(model.sizeBytes)
      expect(createHash('sha256').update(bytes).digest('hex')).toBe(model.sha256)
    }
  })

  it('separates deployed-artifact scores from the historical baseline', () => {
    const form = report.models.filter((model) => model.id.startsWith('form_classifier_'))
    expect(form).toHaveLength(3)
    for (const model of form) {
      expect(model.metrics.n).toBe(24)
      expect(model.baseline).toBeDefined()
      expect(model.reproduction?.status).toBe('artifact-drift')
      expect(model.metrics.matchesStoredReport).toBe(false)
    }
    const recommender = report.models.find((model) => model.id === 'workout_recommendation')
    expect(recommender?.metrics.n).toBe(1427)
    expect(recommender?.reproduction?.status).toBe('exact')
    expect(recommender?.dataset.name).toContain('synthetic')
  })

  it('never claims a form accuracy above chance without naming the small test set', () => {
    for (const model of report.models) {
      expect(model.dataset.sampleCount).toBe(model.metrics.n)
      expect(model.limitations.length).toBeGreaterThan(0)
    }
  })
})
